def pulse(
    *,
    cond_m: float = -10.0,
    cond_t: float = -10.0,
    cond_f: float = -10.0,
    glob_m: float = 0.0,
    glob_t: float = 0.0,
    glob_f: float = 0.0,
    loc_m: float = 0.0,
    loc_t: float = 0.0,
    loc_f: float = 0.0,
    falloff: float = 1.0,
) -> dict[str, Any]:
    return {
        "conditions": {"moisture": cond_m, "temperature": cond_t, "fertility": cond_f},
        "global": {"moisture": glob_m, "temperature": glob_t, "fertility": glob_f},
        "local": {
            "moisture": loc_m,
            "temperature": loc_t,
            "fertility": loc_f,
            "falloff_per_hop": falloff,
        },
    }


def C(
    biome: str,
    note: str,
    *,
    generation_type: str,
    placement_type: str,
    climates: list[str],
    temperature: float,
    vegetation_density: float,
    weight: float,
    cond_temp: int,
    delta_temp: int,
    cond_humidity: int,
    delta_humidity: int,
    cond_fertility: int,
    delta_fertility: int,
    stat_generator: bool = False,
    stats: dict[str, Any] | None = None,
    ceiling_patch_min: float | None = None,
    ceiling_patch_max: float | None = None,
    island_max_radius: float | None = None,
) -> dict[str, Any]:
    body: dict[str, Any] = {
        "_note": note,
        "biome": biome,
        "generation_type": generation_type,
        "placement_type": placement_type,
        "climates": list(climates),
        "systems": [],
        "dimension": "overworld",
        "temperature": temperature,
        "vegetation_density": vegetation_density,
        "weight": weight,
        "stat_generator": stat_generator,
        "auto_generated": False,
        "cond_temp": cond_temp,
        "delta_temp": delta_temp,
        "cond_humidity": cond_humidity,
        "delta_humidity": delta_humidity,
        "cond_fertility": cond_fertility,
        "delta_fertility": delta_fertility,
        "stats": stats if stats is not None else pulse(),
    }
    if ceiling_patch_min is not None:
        body["ceiling_patch_min"] = ceiling_patch_min
    if ceiling_patch_max is not None:
        body["ceiling_patch_max"] = ceiling_patch_max
    if island_max_radius is not None:
        body["island_max_radius"] = island_max_radius
    return body


