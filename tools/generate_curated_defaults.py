def plains_dales(w_p=1.0, w_d=0.6, w_if=0.5, w_s=0.0) -> dict[str, float]:
    out = {"plains": w_p, "dales": w_d, "island_flats": w_if}
    if w_s > 0:
        out["steppe"] = w_s
    return out


